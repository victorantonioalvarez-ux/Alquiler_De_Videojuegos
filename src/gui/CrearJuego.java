    private void actualizarUnidades(int i) {
        if (casillas[i].isSelected()) {
            unidades[i].setEnabled(true);
            unidades[i].setValue(1);
        } else {
            unidades[i].setEnabled(false);
            unidades[i].setValue(0);
        }
    }
